    suspend fun getAnalyticsData(lecturerId: String): AnalyticsData {
        val codes = codesByLecturerOnce(lecturerId)
        val codeExpiryById = codes.associate { it.id to it.expiresAt }
        val codeCourseById = codes.associate { it.id to it.courseCode }

        val allSubmissions = mutableListOf<SubmissionEntity>()
        val codeIds = codes.map { it.id }
        if (codeIds.isNotEmpty()) {
            val snapshots = coroutineScope {
                codeIds.chunked(30).map { batch ->
                    async { submissionsRef.whereIn("codeId", batch).get().await() }
                }.awaitAll()
            }
            snapshots.forEach { snapshot ->
                allSubmissions.addAll(snapshot.documents.mapNotNull { it.toSubmissionEntity() })
            }
        }

        val total = allSubmissions.size
        val gradedSubmissions = allSubmissions.filter { it.isGraded }
        val gradedRate = if (total == 0) 0 else (gradedSubmissions.size * 100) / total

        val lateCount = allSubmissions.count { submission ->
            val expiry = codeExpiryById[submission.codeId]
            expiry != null && submission.submittedAt > expiry
        }
        val lateRate = if (total == 0) 0 else (lateCount * 100) / total

        val averageGrade = if (gradedSubmissions.isEmpty()) {
            null
        } else {
            gradedSubmissions.mapNotNull { it.totalScore }.average()
        }

        val buckets = listOf(
            "90-100" to (90..100),
            "80-89" to (80..89),
            "70-79" to (70..79),
            "60-69" to (60..69),
            "Below 60" to (0..59)
        )
        val distribution = buckets.map { (label, range) ->
            label to gradedSubmissions.count { (it.totalScore ?: -1) in range }
        }

        val byCourse = allSubmissions
            .groupBy { codeCourseById[it.codeId] ?: "Unknown" }
            .map { (courseCode, subs) -> courseCode to subs.size }
            .sortedByDescending { it.second }

        return AnalyticsData(
            totalSubmissions = total,
            averageGrade = averageGrade,
            gradedRatePercent = gradedRate,
            lateRatePercent = lateRate,
            gradeDistribution = distribution,
            submissionsByCourse = byCourse
        )
    }

    suspend fun getLecturerAnalytics(lecturerId: String): LecturerAnalyticsData {
        val codesSnapshot = codesRef.whereEqualTo("createdByLecturerId", lecturerId).get().await()
        val codes = codesSnapshot.documents.mapNotNull { it.toCodeEntity() }
        val codeIds = codes.map { it.id }

        if (codeIds.isEmpty()) {
            return LecturerAnalyticsData(
                LecturerAnalyticsStats(0, 0.0, 0, 0),
                emptyList(),
                emptyList()
            )
        }

        val submissions = mutableListOf<SubmissionEntity>()
        codeIds.chunked(10).forEach { chunk ->
            val snap = submissionsRef.whereIn("codeId", chunk).get().await()
            submissions += snap.documents.mapNotNull { it.toSubmissionEntity() }
        }

        val completionRate = if (submissions.isEmpty()) 0
        else (submissions.count { it.isConfirmed } * 100) / submissions.size

        val graded = submissions.filter { it.gradedAt != null }
        val averageGrade = if (graded.isEmpty()) 0.0
        else graded.map {
            (it.correctnessScore ?: 0) + (it.codeQualityScore ?: 0) +
                    (it.documentationScore ?: 0) + (it.testingScore ?: 0)
        }.average()

        val lateCount = submissions.count { sub ->
            val code = codes.find { it.id == sub.codeId }
            code != null && sub.submittedAt > code.expiresAt
        }
        val lateSubmissionsPercent = if (submissions.isEmpty()) 0
        else (lateCount * 100) / submissions.size

        val distinctSubmitters = submissions.map { it.studentId }.distinct().size
        val allStudentsSnapshot = usersRef.whereEqualTo("role", UserRole.STUDENT.name).get().await()
        val totalStudents = allStudentsSnapshot.size()
        val studentParticipation = if (totalStudents == 0) 0
        else (distinctSubmitters * 100) / totalStudents

        val dayFormat = java.text.SimpleDateFormat("EEE", java.util.Locale.getDefault())
        val trend = (6 downTo 0).map { daysAgo ->
            val dayStart = java.util.Calendar.getInstance().apply {
                add(java.util.Calendar.DAY_OF_YEAR, -daysAgo)
                set(java.util.Calendar.HOUR_OF_DAY, 0); set(java.util.Calendar.MINUTE, 0)
                set(java.util.Calendar.SECOND, 0); set(java.util.Calendar.MILLISECOND, 0)
            }.timeInMillis
            val dayEnd = dayStart + (24 * 60 * 60 * 1000)
            val label = dayFormat.format(java.util.Date(dayStart))
            val count = submissions.count { it.submittedAt in dayStart until dayEnd }
            SubmissionTrendPoint(label, count)
        }

        val buckets = listOf(
            "A" to (80..100), "B" to (70..79), "C" to (60..69), "D" to (50..59), "F" to (0..49)
        )
        val gradeDistribution = buckets.map { (label, range) ->
            val count = graded.count { sub ->
                val total = (sub.correctnessScore ?: 0) + (sub.codeQualityScore ?: 0) +
                        (sub.documentationScore ?: 0) + (sub.testingScore ?: 0)
                total in range
            }
            GradeBucket(label, count)
        }

        return LecturerAnalyticsData(
            LecturerAnalyticsStats(completionRate, averageGrade, lateSubmissionsPercent, studentParticipation),
            trend,
            gradeDistribution
        )
    }

    suspend fun getLecturerDashboardData(lecturerId: String): LecturerDashboardData {
        val codesSnapshot = codesRef.whereEqualTo("createdByLecturerId", lecturerId).get().await()
        val codes = codesSnapshot.documents.mapNotNull { it.toCodeEntity() }
        val codeIds = codes.map { it.id }

        if (codeIds.isEmpty()) {
            return LecturerDashboardData(DashboardStats(0, 0, 0, 0), emptyList(), emptyList())
        }

        val submissions = mutableListOf<SubmissionEntity>()
        codeIds.chunked(10).forEach { chunk ->
            val snap = submissionsRef.whereIn("codeId", chunk).get().await()
            submissions += snap.documents.mapNotNull { it.toSubmissionEntity() }
        }

        val now = System.currentTimeMillis()
        val weekAgo = now - (7L * 24 * 60 * 60 * 1000)

        val activeCourses = codes.count { it.expiresAt > now }
        val pendingGrading = submissions.count { it.gradedAt == null }
        val totalStudents = submissions.map { it.studentId }.distinct().size
        val submissionsThisWeek = submissions.count { it.submittedAt >= weekAgo }

        val recentSubmissions = submissions
            .sortedByDescending { it.submittedAt }
            .take(5)
            .map { sub ->
                val code = codes.find { it.id == sub.codeId }
                val status = when {
                    sub.gradedAt != null -> "Graded"
                    code != null && sub.submittedAt > code.expiresAt -> "Late"
                    else -> "Pending"
                }
                RecentSubmissionItem(sub.studentName, sub.assignmentTitle, status)
            }

        val upcomingDeadlines = codes
            .filter { it.expiresAt > now }
            .sortedBy { it.expiresAt }
            .take(5)
            .map { UpcomingDeadlineItem(it.assignmentTitle, it.expiresAt) }

        return LecturerDashboardData(
            DashboardStats(activeCourses, pendingGrading, totalStudents, submissionsThisWeek),
            recentSubmissions,
            upcomingDeadlines
        )
    }

