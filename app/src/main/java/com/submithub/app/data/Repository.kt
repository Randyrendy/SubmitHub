    suspend fun login(id: String, password: String, role: UserRole): UserEntity? {
        val trimmedId = id.trim()

        if (role == UserRole.ADMIN && trimmedId.equals("admin", ignoreCase = true) && password == "admin123") {
            return UserEntity(
                id = "admin",
                name = "Administrator",
                role = UserRole.ADMIN,
                password = password,
                identifierLabel = "Super Admin"
            )
        }

        val snapshot = usersRef
            .whereEqualTo("id", trimmedId)
            .whereEqualTo("role", role.name)
            .get()
            .await()

        val doc = snapshot.documents.firstOrNull() ?: return null

        val storedPassword = doc.getString("password") ?: return null
        if (storedPassword != password) return null

        return UserEntity(
            id = doc.getString("id") ?: trimmedId,
            name = doc.getString("name") ?: "",
            role = role,
            password = storedPassword,
            identifierLabel = doc.getString("identifierLabel") ?: ""
        )
    }

