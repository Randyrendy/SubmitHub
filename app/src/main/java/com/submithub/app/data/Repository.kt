    suspend fun migrateOldAccountsToAuth(): List<String> {
        val log = mutableListOf<String>()
        val snapshot = usersRef.get().await()

        for (doc in snapshot.documents) {
            val password = doc.getString("password")
            if (password.isNullOrBlank()) continue // already migrated, skip

            val idField = doc.getString("id") ?: continue
            val roleStr = doc.getString("role") ?: continue
            val role = try { UserRole.valueOf(roleStr) } catch (e: Exception) { continue }
            val name = doc.getString("name") ?: ""
            val identifierLabel = doc.getString("identifierLabel") ?: ""

            try {
                val email = com.submithub.app.util.AuthEmailHelper.syntheticEmailFor(role, idField)
                val authResult = com.google.firebase.auth.FirebaseAuth.getInstance()
                    .createUserWithEmailAndPassword(email, password)
                    .await()
                val uid = authResult.user?.uid ?: continue

                usersRef.document(uid).set(
                    mapOf(
                        "id" to idField,
                        "name" to name,
                        "role" to role.name,
                        "identifierLabel" to identifierLabel
                    )
                ).await()

                doc.reference.delete().await()
                log.add("✅ Migrated $idField ($roleStr)")
            } catch (e: Exception) {
                log.add("❌ Failed $idField: ${e.message}")
            }
        }

        return log
    }

    suspend fun registerUserWithAuth(
        role: UserRole,
        id: String,
        name: String,
        password: String,
        identifierLabel: String
    ): UserEntity {
        val email = com.submithub.app.util.AuthEmailHelper.syntheticEmailFor(role, id)
        val authResult = com.google.firebase.auth.FirebaseAuth.getInstance()
            .createUserWithEmailAndPassword(email, password)
            .await()

        val uid = authResult.user?.uid ?: throw IllegalStateException("Account creation failed")

        val userMap = mapOf(
            "id" to id.trim(),
            "name" to name,
            "role" to role.name,
            "identifierLabel" to identifierLabel
        )
        usersRef.document(uid).set(userMap).await()

        return UserEntity(
            id = id.trim(),
            name = name,
            role = role,
            password = "",
            identifierLabel = identifierLabel
        )
    }

    suspend fun loginWithAuth(role: UserRole, id: String, password: String): UserEntity? {
        val email = com.submithub.app.util.AuthEmailHelper.syntheticEmailFor(role, id)

        val authResult = try {
            com.google.firebase.auth.FirebaseAuth.getInstance()
                .signInWithEmailAndPassword(email, password)
                .await()
        } catch (e: Exception) {
            return null
        }

        val uid = authResult.user?.uid ?: return null
        val doc = usersRef.document(uid).get().await()
        if (!doc.exists()) return null

        return UserEntity(
            id = doc.getString("id") ?: id.trim(),
            name = doc.getString("name") ?: "",
            role = role,
            password = "",
            identifierLabel = doc.getString("identifierLabel") ?: ""
        )
    }

