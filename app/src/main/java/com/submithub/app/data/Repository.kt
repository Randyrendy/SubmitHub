    suspend fun gradeSubmission(
        submissionId: String,
        correctnessScore: Int,
        codeQualityScore: Int,
        documentationScore: Int,
        testingScore: Int,
        feedback: String
    ) {
        submissionsRef.document(submissionId).update(
            mapOf(
                "correctnessScore" to correctnessScore,
                "codeQualityScore" to codeQualityScore,
                "documentationScore" to documentationScore,
                "testingScore" to testingScore,
                "feedback" to feedback,
                "gradedAt" to System.currentTimeMillis()
            )
        ).await()
    }

    suspend fun userExists(id: String): Boolean {
        val snapshot = usersRef.whereEqualTo("id", id.trim()).get().await()
        return !snapshot.isEmpty
    }

