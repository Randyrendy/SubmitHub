/**
 * Firestore-backed data layer. Replaces the old local Room database so that
 * codes generated by a lecturer, and submissions made by students, are
 * visible in real time from any device.
 *
 * Firestore collections used:
 *  - users        (doc id = auto-generated; the human-entered id/staff id/matric no
 *                   is stored as a FIELD called "id", since matric numbers and staff
 *                   IDs often contain slashes, which are illegal in Firestore document
 *                   paths/IDs)
 *  - codes        (doc id = the generated assignment code)
 *  - submissions  (auto id)
 */
class Repository {

